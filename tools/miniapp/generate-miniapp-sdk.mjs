import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const schemaPath = path.join(
  root,
  "packages",
  "miniapp-contracts",
  "api",
  "miniapp.operations.json",
);
const outputPath = path.join(
  root,
  "packages",
  "miniapp-contracts",
  "src",
  "generated",
  "miniapp-api.generated.ts",
);
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
if (schema.schemaVersion !== "starward-miniapp-api-operations-current")
  throw new Error("miniapp_sdk_schema_version_invalid");
if (!Array.isArray(schema.operations) || schema.operations.length === 0)
  throw new Error("miniapp_sdk_operations_missing");
const ids = new Set();
for (const operation of schema.operations) {
  if (!/^[a-z][A-Za-z0-9]+$/u.test(operation.id) || ids.has(operation.id))
    throw new Error(`miniapp_sdk_operation_id_invalid:${operation.id}`);
  ids.add(operation.id);
  if (!["GET", "POST", "PUT", "PATCH", "DELETE"].includes(operation.method))
    throw new Error(`miniapp_sdk_method_invalid:${operation.id}`);
  if (!/^\/[A-Za-z0-9_/{}/-]*$/u.test(operation.path))
    throw new Error(`miniapp_sdk_path_invalid:${operation.id}`);
  for (const name of [operation.requestType, operation.responseType])
    if (name !== "void" && !/^[A-Z][A-Za-z0-9]+$/u.test(name))
      throw new Error(`miniapp_sdk_type_invalid:${operation.id}`);
}
const imports = [...new Set(schema.operations.flatMap((operation) => [
  operation.requestType,
  operation.responseType,
]).filter((name) => name !== "void"))].sort();
const operationRows = schema.operations.map(
  (operation) =>
    `  ${operation.id}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`,
);
const typeRows = schema.operations.map(
  (operation) =>
    `  ${operation.id}: { request: ${operation.requestType}; response: ApiEnvelope<${operation.responseType}> };`,
);
const output = `/* AUTO-GENERATED by tools/miniapp/generate-miniapp-sdk.mjs. DO NOT EDIT. */\n` +
  `import type { ApiEnvelope, ${imports.join(", ")} } from "../index-types.ts";\n\n` +
  `export const MINIAPP_API_BASE_PATH = ${JSON.stringify(schema.basePath)} as const;\n` +
  `export const MINIAPP_API_OPERATIONS = {\n${operationRows.join("\n")}\n} as const;\n\n` +
  `export interface MiniappApiOperationTypes {\n${typeRows.join("\n")}\n}\n\n` +
  `export type MiniappApiOperationId = keyof MiniappApiOperationTypes;\n` +
  `export type MiniappApiRequest<K extends MiniappApiOperationId> = MiniappApiOperationTypes[K]["request"];\n` +
  `export type MiniappApiResponse<K extends MiniappApiOperationId> = MiniappApiOperationTypes[K]["response"];\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) throw new Error("miniapp_generated_sdk_stale");
  process.stdout.write("miniapp_generated_sdk_current\n");
} else {
  await writeFile(outputPath, output);
  process.stdout.write(`${outputPath}\n`);
}
