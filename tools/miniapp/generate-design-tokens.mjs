import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const marker = /<!-- miniapp-tokens:start -->\s*```json\s*([\s\S]*?)\s*```\s*<!-- miniapp-tokens:end -->/gu;
const requiredType = ["page-title", "spot-title", "section", "body", "body-secondary", "action", "search", "metadata", "data", "article", "critical", "display"];

export function readDesignTokens(design) {
  const matches = [...design.matchAll(marker)];
  assert.equal(matches.length, 1, "DESIGN.md must own exactly one Mini Program token block");
  const tokens = JSON.parse(matches[0][1]);
  assert.equal(tokens.schema, 1);
  assert.equal(tokens.unit, "logical-px");
  for (const name of requiredType) {
    const role = tokens.type[name];
    assert(role && Number.isFinite(role.size) && role.size >= 12, `${name}: readable logical font size required`);
    assert(role.line >= role.size && [400, 500, 600].includes(role.weight), `${name}: invalid line/weight`);
  }
  assert(tokens.geometry["target-min"] >= 44, "hit targets must remain >=44 logical px on narrow phones");
  for (const mode of ["day", "night", "observation"]) {
    assert(tokens.themes[mode], `missing ${mode} theme`);
    assert.deepEqual(Object.keys(tokens.themes[mode]), Object.keys(tokens.themes.day), `${mode}: role parity`);
  }
  for (const [name, value] of Object.entries(tokens.geometry)) {
    assert(Number.isFinite(value) && value >= 0, `${name}: invalid geometry`);
  }
  return tokens;
}

export function renderDesignTokens(tokens) {
  const digest = createHash("sha256").update(JSON.stringify(tokens)).digest("hex");
  const header = `// Generated by tools/miniapp/generate-design-tokens.mjs from DESIGN.md. Do not edit.\n// Token SHA256: ${digest}\n`;
  const lines = [header, `$font-native: ${tokens.fontFamily};`, "", "page,", ".theme-page {"];
  for (const [name, role] of Object.entries(tokens.type)) {
    lines.push(`  --type-${name}-size: ${role.size}Px;`, `  --type-${name}-line: ${role.line}Px;`, `  --type-${name}-weight: ${role.weight};`);
  }
  for (const [name, value] of Object.entries(tokens.geometry)) lines.push(`  --${name}: ${value}Px;`);
  lines.push("}", "", ".large-text {");
  for (const [name, role] of Object.entries(tokens.type)) {
    lines.push(`  --type-${name}-size: ${role.size * 2}Px;`, `  --type-${name}-line: ${role.line * 2}Px;`);
  }
  lines.push("}");
  for (const [mode, roles] of Object.entries(tokens.themes)) {
    lines.push("", mode === "day" ? "page,\n.theme-day {" : `.theme-${mode} {`);
    for (const [name, value] of Object.entries(roles)) lines.push(`  --${name}: ${value};`);
    lines.push("}");
  }
  const chrome = Object.fromEntries(Object.entries(tokens.themes).map(([mode, roles]) => [mode.toUpperCase(), {
    canvas: roles.canvas.toUpperCase(),
    color: roles[mode === "night" ? "text-tertiary" : "text-secondary"].toUpperCase(),
    selectedColor: roles["choice-selected-label"].toUpperCase(),
    backgroundColor: roles.surface.toUpperCase(),
    borderStyle: mode === "day" ? "white" : "black",
    suffix: mode === "day" ? "" : `-${mode}`,
  }]));
  const ts = `${header}\nexport const MINIAPP_DESIGN = ${JSON.stringify(tokens, null, 2)} as const;\n\nexport const NATIVE_CHROME_THEME = ${JSON.stringify(chrome, null, 2)} as const;\n`;
  return new Map([
    ["apps/wechat-miniapp/src/styles/tokens.scss", `${lines.join("\n")}\n`],
    ["apps/wechat-miniapp/src/theme/design-tokens.ts", ts],
  ]);
}

export async function generateDesignTokens({ check = false, repoRoot = root } = {}) {
  const tokens = readDesignTokens(await readFile(path.join(repoRoot, "DESIGN.md"), "utf8"));
  for (const [relative, contents] of renderDesignTokens(tokens)) {
    const file = path.join(repoRoot, relative);
    if (check) assert.equal(await readFile(file, "utf8"), contents, `${relative}: regenerate with npm run miniapp:design-tokens`);
    else await writeFile(file, contents);
  }
  return tokens;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateDesignTokens({ check: process.argv.includes("--check") });
  console.log(process.argv.includes("--check") ? "Mini Program design tokens are current." : "Generated Mini Program SCSS and native tokens.");
}
