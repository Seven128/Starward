class CanonicalChunkMetadataTest(unittest.TestCase):
    def test_projected_children_match_original_dataset_window_transform_exactly(self) -> None:
        # Metadata surrogate with the actual qualified EOG affine and offsets.
        # Dataset.window_transform needs no source-pixel allocation or read.
        full_transform = Affine(0.0041666667, 0, -180.00208333335,
                                0, -0.0041666667, 75.00208333335)
        source_window = Window(70198, 11504, 1354, 1232)
        window = {"grid": "gcj02-mercator-pixel-centres-v1", "tilePixels": 256,
                  "zoom": 6, "x": 52, "y": 27, "columns": 1, "rows": 1}
        area, branch = np.ones((256, 256), dtype="<f8").tobytes(), bytes(256 * 256)
        calls: list[Window] = []
        with tempfile.TemporaryDirectory(prefix="starward-eog-canonical-metadata-") as temporary, MemoryFile() as memory:
            directory = Path(temporary)
            with memory.open(driver="GTiff", width=2, height=2, count=1, dtype="uint8", crs="EPSG:4326",
                             transform=full_transform) as dataset:
                source = RasterGrid(window=source_window, transform=dataset.window_transform(source_window),
                    resolution_degrees=(full_transform.a, -full_transform.e), width=1354, height=1232,
                    raster_transform=dataset.transform)

                def project(spec: dict, folder: Path) -> dict:
                    row, column = map(int, folder.name.split("-"))
                    declared = spec["source"]
                    absolute = Window(source_window.col_off + column, source_window.row_off + row,
                                      declared["width"], declared["height"])
                    canonical = dataset.window_transform(absolute)
                    self.assertEqual(declared, {"width": int(absolute.width), "height": int(absolute.height),
                        "west": canonical.c, "north": canonical.f, "longitudeStep": canonical.a, "latitudeStep": canonical.e},
                        f"the preparer must project the exact window subsequently read from the original TIFF: {absolute}")
                    calls.append(absolute)
                    # Only target/header stubs are needed to exercise the real
                    # partition/project calls. No dense mesh or numeric mass is
                    # generated by this metadata-identity regression.
                    folder.mkdir(parents=True, exist_ok=True)
                    files = {}
                    for key, raw, suffix in (("targetArea", area, "f64"), ("targetBranch", branch, "u8")):
                        file = f"{key}.{suffix}"
                        (folder / file).write_bytes(raw)
                        files[key] = {"file": file, "sha256": sha256_bytes(raw), "bytes": len(raw)}
                    child = {"schemaVersion": "starward-nightlight-warp-grid-v1", "grid": window["grid"],
                        "originalSource": declared, "sourceSubdivision": spec["sourceSubdivision"], "window": spec["window"],
                        "width": 256, "height": 256, "byteOrder": "little-endian",
                        "sourceGeolocationConvention": "TOP_LEFT_CORNER", "affine": [1, 0, 0, 0, -1, 0],
                        "boundsGcj02": {"west": 0, "south": 0, "east": 1, "north": 1}, "files": files}
                    (folder / "warp-grid.json").write_text(canonical_json(child) + "\n", encoding="utf8")
                    return child

                grid = chunked.prepare_chunk_geometry(source, window, 3, directory, project, preparer.write_immutable)
        self.assertEqual(len(calls), 9)
        self.assertTrue(any(item.col_off == source_window.col_off + 1024 for item in calls),
                        "cover the real column whose cropped-affine translation previously differed by one ulp")
        self.assertEqual(max(item["sourceWindow"][2] * item["sourceWindow"][3] * 9 for item in grid["sourceChunks"]), 2368521)


class ChunkPreparationTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.temporary = tempfile.TemporaryDirectory(prefix="starward-eog-chunk-preparation-")
        cls.root = Path(cls.temporary.name)
        cls.legacy, _ = prepare_fixture(cls.root)
        # Add real input masks and insufficient counts to the public synthetic
        # source. The original fixture remains an explicitly synthetic source.
        with rasterio.open(cls.root / "radiance.tif", "r+") as image:
            values = image.read(1)
            values[:, 56:] = 0
            values[8:16, :] = -9999
            image.nodata = -9999
            image.write(values, 1)
        with rasterio.open(cls.root / "coverage.tif", "r+") as image:
            values = image.read(1)
            values[16:32, :] = 0
            image.write(values, 1)
        raw = json.loads(cls.legacy.read_bytes())
        raw["radiance"]["sha256"] = sha256_file(cls.root / "radiance.tif")
        raw["cloudFreeCoverage"]["sha256"] = sha256_file(cls.root / "coverage.tif")
        cls.legacy.write_text(json.dumps(raw), encoding="utf-8")
        cls.windows = [{"grid": "gcj02-mercator-pixel-centres-v1", "tilePixels": 256,
                        "zoom": 9, "x": 418, "y": 222, "columns": 2, "rows": 1}]
        cls.dense, cls.output = cls.root / "dense", cls.root / "chunked"
        preparer.prepare_release(cls.legacy, "eog-dense-integration-test", cls.windows, cls.dense)
        with mock.patch.object(preparer, "requires_chunked_source", return_value=True), mock.patch.object(chunked, "SOURCE_CORE_SIDE", 32), \
                mock.patch.object(preparer, "read_selection", side_effect=AssertionError("the chunk route must not load the complete AOI")), \
                mock.patch.object(chunked, "read_selection", wraps=chunked.read_selection) as reads:
            cls.result = preparer.prepare_release(cls.legacy, "eog-chunk-integration-test", cls.windows, cls.output)
            cls.read_windows = [call.kwargs["source_window"] for call in reads.call_args_list]
        cls.manifest = load_manifest(cls.output / "manifest.json")
        cls.inventory = publication.read_inventory(cls.manifest, read_grid(cls.manifest).resolution_degrees)
        cls.entry = cls.inventory["assets"][0]
        cls.proof = json.loads((cls.output / (cls.entry["file"] + ".json")).read_bytes())

    @classmethod
    def tearDownClass(cls) -> None:
        cls.temporary.cleanup()

    def test_actual_preparer_streams_cores_and_keeps_all_six_bands_and_final_pixels(self) -> None:
        self.assertEqual(self.proof["schemaVersion"], "starward-fixed-nightlight-raster-v3")
        self.assertEqual(self.proof["grid"]["schemaVersion"], chunked.CHUNK_GRID_SCHEMA)
        self.assertEqual(self.proof["derivation"], "GEOS_PHYSICAL_AREA_CHUNKED_INTERSECTION")
        self.assertEqual(len(self.read_windows), 8, "two cells read four cores each; composition reads no source pixels")
        self.assertTrue(all(window.width <= 33 and window.height <= 33 for window in self.read_windows))
        reference_inventory = json.loads((self.dense / "inventory.json").read_bytes())
        reference = json.loads((self.dense / (reference_inventory["assets"][0]["file"] + ".json")).read_bytes())
        self.assertEqual(reference["schemaVersion"], "starward-fixed-nightlight-raster-v2")
        self.assertEqual(self.proof["numeric"]["bands"], reference["numeric"]["bands"])
        with rasterio.open(self.output / self.proof["numeric"]["file"]) as image, rasterio.open(self.dense / reference["numeric"]["file"]) as original:
            actual, expected = image.read(), original.read()
            self.assertEqual(image.count, 6)
            np.testing.assert_array_equal(actual[5], expected[5])
            # Independently generated local geometry may round shared anchors
            # at a few ulps. This is much smaller than the unchanged area-policy
            # tolerance and must not move quality or cartographic pixels.
            np.testing.assert_allclose(actual[:5], expected[:5], rtol=1e-9, atol=1e-11, equal_nan=True)
        self.assertEqual((self.output / self.proof["image"]["file"]).read_bytes(), (self.dense / reference["image"]["file"]).read_bytes())
        for quality in (self.proof["quality"], reference["quality"]):
            self.assertLessEqual(quality["maximumAreaExcessFraction"], fixed.POLICY["qualityPolicy"]["areaFractionNumericalTolerance"])
        self.assertEqual({key: value for key, value in self.proof["quality"].items() if key != "maximumAreaExcessFraction"},
                         {key: value for key, value in reference["quality"].items() if key != "maximumAreaExcessFraction"})
        self.assertGreater(self.proof["quality"]["validZeroPixelCount"], 0)
        self.assertGreater(self.proof["quality"]["qualityMaskCounts"]["3"], 0)
        self.assertGreater(self.proof["quality"]["qualityMaskCounts"]["4"], 0)
        self.assertFalse(self.result["databasePublication"])

    def test_full_new_proof_passes_existing_index_and_shared_display_consumer(self) -> None:
        target = self.root / "sharded"
        result = sharded.prepare_index([self.output / "manifest.json"], target)
        found = sharded.read_window(target, result["index"], self.entry["key"])
        self.assertEqual(found["numeric"]["sha256"], self.proof["numeric"]["sha256"])
        self.assertEqual(len(found["numeric"]["bands"]), 6)
        self.assertEqual(found["quality"], self.proof["quality"])
        self.assertGreater(found["display"]["image"]["bytes"], 0)

    def test_chunked_composition_copies_existing_six_band_pixels(self) -> None:
        proofs = [json.loads((self.output / (entry["file"] + ".json")).read_bytes()) for entry in self.inventory["assets"]]
        composition = next(proof for proof in proofs if proof["grid"]["window"]["columns"] == 2)
        self.assertEqual(composition["schemaVersion"], "starward-fixed-nightlight-raster-v3")
        self.assertEqual(composition["derivation"], "NUMERIC_FIXED_CELL_COMPOSITION")
        with rasterio.open(self.output / composition["numeric"]["file"]) as image:
            values = image.read()
        for proof in proofs:
            if proof is composition:
                continue
            column = (proof["grid"]["window"]["x"] - composition["grid"]["window"]["x"]) * 256
            with rasterio.open(self.output / proof["numeric"]["file"]) as image:
                np.testing.assert_array_equal(values[:, :, column:column + 256], image.read())

    def test_incomplete_overlap_halo_and_bad_descriptor_fail_before_sealing(self) -> None:
        for mutation in ("gap", "overlap", "equal-area-overlap", "halo", "descriptor", "version"):
            grid = copy.deepcopy(self.proof["grid"])
            if mutation == "gap":
                grid["sourceChunks"].pop()
            elif mutation == "overlap":
                grid["sourceChunks"][-1] = copy.deepcopy(grid["sourceChunks"][0])
            elif mutation == "equal-area-overlap":
                # Unique origin/file names and equal summed area can still
                # hide a two-dimensional overlap plus a missing column.
                step = grid["sourceSubdivision"]
                grid["sourceChunks"][0]["sourceWindow"][2] += 1
                grid["sourceChunks"][0]["core"][3] += step
                grid["sourceChunks"][1]["core"][3] -= step
            elif mutation == "halo":
                grid["sourceChunks"][0]["sourceWindow"][2] -= 1
            elif mutation == "descriptor":
                grid["sourceChunks"][0]["geometry"]["file"] = "../untrusted.json"
            else:
                grid["schemaVersion"] = "starward-nightlight-warp-grid-v99"
            with self.subTest(mutation=mutation), self.assertRaises(PipelineError):
                chunked.validate_chunk_grid(grid)
        incomplete = self.root / "incomplete"
        with mock.patch.object(preparer, "requires_chunked_source", return_value=True), mock.patch.object(chunked, "SOURCE_CORE_SIDE", 32):
            # Inject at the original preparer's actual numerical boundary: no
            # inventory or manifest can be sealed after a failed source read.
            with mock.patch.object(preparer, "prepare_chunked_window", side_effect=PipelineError("source_read_failed")):
                with self.assertRaisesRegex(PipelineError, "source_read_failed"):
                    preparer.prepare_release(self.legacy, "eog-incomplete-integration-test", self.windows, incomplete)
        self.assertFalse((incomplete / "inventory.json").exists())
        self.assertFalse((incomplete / "manifest.json").exists())

    def test_validated_replay_does_not_warp_or_replace_existing_assets(self) -> None:
        before = {name: (self.output / name).read_bytes() for name in ("manifest.json", "inventory.json")}
        with mock.patch.object(preparer, "requires_chunked_source", return_value=True), mock.patch.object(chunked, "SOURCE_CORE_SIDE", 32), \
                mock.patch.object(preparer, "prepare_chunked_window", side_effect=AssertionError("completed cells must not be warped again")):
            result = preparer.prepare_release(self.legacy, "eog-chunk-integration-test", self.windows, self.output)
        self.assertEqual(result["reusedValidatedAssetCount"], 3)
        for name, raw in before.items():
            self.assertEqual((self.output / name).read_bytes(), raw)


